/**
 * Turns ./migrations/*.sql into src/migrations.generated.ts. Run by `pnpm generate`.
 * The app applies migrations from that module, so nothing reads the filesystem at
 * runtime: a bundled serverless function has no ./migrations folder to read.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const journal = JSON.parse(readFileSync(join(root, "migrations/meta/_journal.json"), "utf8")) as { entries: Array<{ idx: number; tag: string }> };
const migrations = journal.entries.sort((a, b) => a.idx - b.idx).map((entry) => ({ tag: entry.tag, sql: readFileSync(join(root, "migrations", `${entry.tag}.sql`), "utf8") }));

writeFileSync(
  join(root, "src/migrations.generated.ts"),
  `// GENERATED by scripts/embed-migrations.ts from ./migrations. Do not edit by hand; run \`pnpm --filter @repo/db generate\`.\nexport const MIGRATIONS: ReadonlyArray<{ tag: string; sql: string }> = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`embedded ${migrations.length} migration(s)`);
